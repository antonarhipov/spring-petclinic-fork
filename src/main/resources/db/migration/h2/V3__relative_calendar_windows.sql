CREATE TABLE request_availability_windows (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id INTEGER NOT NULL,
  window_order INTEGER NOT NULL,
  window_kind VARCHAR(20) NOT NULL,
  expression_type VARCHAR(30) NOT NULL,
  explicit_date DATE,
  day_of_week INTEGER,
  week_offset INTEGER,
  month_offset INTEGER,
  month_of_year INTEGER,
  ordinal_week VARCHAR(20),
  start_time TIME,
  end_time TIME,
  named_period VARCHAR(20),
  CONSTRAINT fk_availability_windows_request FOREIGN KEY (request_id) REFERENCES scheduling_requests (id) ON DELETE CASCADE
);

CREATE INDEX idx_availability_windows_request ON request_availability_windows (request_id, window_order);

CREATE TABLE request_availability_intervals (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id INTEGER NOT NULL,
  source_window_id INTEGER,
  window_kind VARCHAR(20) NOT NULL,
  start_instant TIMESTAMP NOT NULL,
  end_instant TIMESTAMP NOT NULL,
  CONSTRAINT fk_availability_intervals_request FOREIGN KEY (request_id) REFERENCES scheduling_requests (id) ON DELETE CASCADE,
  CONSTRAINT fk_availability_intervals_source FOREIGN KEY (source_window_id) REFERENCES request_availability_windows (id) ON DELETE CASCADE
);

CREATE INDEX idx_availability_intervals_request ON request_availability_intervals (request_id, start_instant);
