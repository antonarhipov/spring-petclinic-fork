CREATE TABLE scheduling_requests (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pet_id INTEGER NOT NULL,
  state VARCHAR(32) NOT NULL,
  current_revision_id INTEGER,
