CREATE TABLE appointments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pet_id INTEGER NOT NULL,
  vet_id INTEGER NOT NULL,
  start_at TIMESTAMP WITH TIME ZONE NOT NULL,
  duration_minutes INTEGER NOT NULL,
  source VARCHAR(32) NOT NULL,
  request_id INTEGER,
  revision_id INTEGER,
  offer_id INTEGER UNIQUE,
  owner_agreement VARCHAR(1000),
  status VARCHAR(16) NOT NULL,
  change_reason VARCHAR(64),
  change_note VARCHAR(1000),
  version BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT fk_appointment_pet FOREIGN KEY (pet_id) REFERENCES pets(id),
  CONSTRAINT fk_appointment_vet FOREIGN KEY (vet_id) REFERENCES vets(id),
  CONSTRAINT fk_appointment_request FOREIGN KEY (request_id) REFERENCES scheduling_requests(id),
  CONSTRAINT fk_appointment_revision FOREIGN KEY (revision_id) REFERENCES request_revisions(id),
  CONSTRAINT fk_appointment_offer FOREIGN KEY (offer_id) REFERENCES appointment_offers(id)
);
