CREATE TABLE clinic_opening_hours (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  settings_id  INTEGER NOT NULL,
  weekday      VARCHAR(16) NOT NULL,
  open_time    TIME,
  close_time   TIME,
  CONSTRAINT fk_clinic_opening_hours_settings FOREIGN KEY (settings_id) REFERENCES clinic_settings (id),
  CONSTRAINT uq_clinic_opening_hours_weekday UNIQUE (settings_id, weekday),
  CONSTRAINT ck_clinic_opening_hours_values CHECK (
    (open_time IS NULL AND close_time IS NULL) OR (open_time IS NOT NULL AND close_time > open_time)
  )
);

CREATE TABLE vet_working_blocks (
