CREATE TABLE clinic_settings (
  id                       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_horizon_days     INTEGER NOT NULL,
  minimum_lead_days        INTEGER NOT NULL,
  minimum_duration_minutes INTEGER NOT NULL,
  default_duration_minutes INTEGER NOT NULL,
  maximum_duration_minutes INTEGER NOT NULL,
  grid_minutes             INTEGER NOT NULL,
  morning_start            TIME NOT NULL,
  morning_end              TIME NOT NULL,
  afternoon_start          TIME NOT NULL,
  afternoon_end            TIME NOT NULL,
