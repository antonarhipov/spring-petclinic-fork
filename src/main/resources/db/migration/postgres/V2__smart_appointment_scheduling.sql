CREATE TABLE IF NOT EXISTS scheduling_requests (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id INT NOT NULL REFERENCES owners(id),
  pet_id INT NOT NULL REFERENCES pets(id),
  status VARCHAR(40) NOT NULL,
  original_text VARCHAR(2000) NULL,
  language VARCHAR(10) DEFAULT 'en' NOT NULL,
  urgent BOOLEAN DEFAULT FALSE NOT NULL,
  care_type VARCHAR(30) NULL,
  required_specialty_id INT NULL REFERENCES specialties(id),
  preferred_vet_id INT NULL REFERENCES vets(id),
  duration_minutes INT NULL,
  preferred_start_window TIMESTAMPTZ NULL,
  preferred_end_window TIMESTAMPTZ NULL,
  owner_horizon_end TIMESTAMPTZ NULL,
  first_queued_at TIMESTAMPTZ NULL,
  fallback_deadline TIMESTAMPTZ NULL,
  last_clarification_reason VARCHAR(255) NULL,
  clarification_count INT DEFAULT 0 NOT NULL,
  ai_summary VARCHAR(1000) NULL,
  full_ai_response TEXT NULL,
  retention_deadline TIMESTAMPTZ NULL,
  purged_at TIMESTAMPTZ NULL,
  consent_given_at TIMESTAMPTZ NULL,
  recovery_required BOOLEAN DEFAULT FALSE NOT NULL,
  version BIGINT DEFAULT 0 NOT NULL,
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_requests_owner_id ON scheduling_requests (owner_id);
CREATE INDEX IF NOT EXISTS idx_requests_status ON scheduling_requests (status);

CREATE TABLE IF NOT EXISTS operations (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token VARCHAR(100) NOT NULL UNIQUE,
  request_id INT NOT NULL REFERENCES scheduling_requests(id),
  operation_type VARCHAR(30) NOT NULL,
  status VARCHAR(30) NOT NULL,
  dispatched_at TIMESTAMPTZ NOT NULL,
  deadline TIMESTAMPTZ NOT NULL,
  attempt_count INT DEFAULT 1 NOT NULL,
  version BIGINT DEFAULT 0 NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_operations_request_id ON operations (request_id);

CREATE TABLE IF NOT EXISTS reservations (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reservation_type VARCHAR(30) NOT NULL,
  status VARCHAR(30) NOT NULL,
  request_id INT NOT NULL REFERENCES scheduling_requests(id),
  owner_id INT NOT NULL REFERENCES owners(id),
  pet_id INT NOT NULL REFERENCES pets(id),
  vet_id INT NOT NULL REFERENCES vets(id),
  start_time TIMESTAMPTZ NOT NULL,
  end_time TIMESTAMPTZ NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  version BIGINT DEFAULT 0 NOT NULL,
  created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_reservations_request_id ON reservations (request_id);
CREATE INDEX IF NOT EXISTS idx_reservations_vet_time ON reservations (vet_id, start_time, end_time);

CREATE TABLE IF NOT EXISTS rejections (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id INT NOT NULL REFERENCES scheduling_requests(id),
  vet_id INT NOT NULL REFERENCES vets(id),
  start_time TIMESTAMPTZ NOT NULL,
  end_time TIMESTAMPTZ NOT NULL,
  reason VARCHAR(255) NULL,
  rejected_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_rejections_request_id ON rejections (request_id);

