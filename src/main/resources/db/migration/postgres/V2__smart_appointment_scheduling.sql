CREATE TABLE accounts (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username VARCHAR(80) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL, role VARCHAR(16) NOT NULL, owner_id INT UNIQUE REFERENCES owners(id),
  must_change_password BOOLEAN NOT NULL DEFAULT FALSE, temporary_password_expires_at TIMESTAMP WITH TIME ZONE,
  failed_sign_in_count INT NOT NULL DEFAULT 0, locked_until TIMESTAMP WITH TIME ZONE, version BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE clinic_scheduling_settings (
  id INT PRIMARY KEY, clinic_zone VARCHAR(64) NOT NULL, booking_horizon_days INT NOT NULL,
  owner_minimum_notice_minutes INT NOT NULL, offer_hold_minutes INT NOT NULL,
  urgent_care_guidance VARCHAR(2000) NOT NULL, version BIGINT NOT NULL DEFAULT 0
);
