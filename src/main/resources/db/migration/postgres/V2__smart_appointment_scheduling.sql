CREATE TABLE IF NOT EXISTS appointments (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  status VARCHAR(30) NOT NULL,
  request_id INT NULL REFERENCES scheduling_requests(id),
  owner_id INT NOT NULL REFERENCES owners(id),
  pet_id INT NOT NULL REFERENCES pets(id),
  vet_id INT NOT NULL REFERENCES vets(id),
  care_type VARCHAR(30) NOT NULL,
  required_specialty_id INT NULL REFERENCES specialties(id),
  start_time TIMESTAMPTZ NOT NULL,
  end_time TIMESTAMPTZ NOT NULL,
  booking_source VARCHAR(30) NOT NULL,
  offline_reason VARCHAR(255) NULL,
  cancellation_reason VARCHAR(255) NULL,
  completed_at TIMESTAMPTZ NULL,
  completion_notes VARCHAR(1000) NULL,
  visit_id INT NULL REFERENCES visits(id),
  version BIGINT DEFAULT 0 NOT NULL,
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_appointments_owner_id ON appointments (owner_id);
CREATE INDEX IF NOT EXISTS idx_appointments_vet_time ON appointments (vet_id, start_time, end_time);

